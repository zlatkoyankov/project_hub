// Builds boards.css: faint "board" backdrops (blueprint, bricks, tiles…) as
// inline SVG masks. Run after editing boards/*.svg:
//   node packages/design-system/scripts/build-boards.mjs
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'boards')
const names = (await readdir(dir)).filter((f) => f.endsWith('.svg')).sort()

const rules = []
for (const file of names) {
  const name = file.replace(/\.svg$/, '')
  const svg = (await readFile(join(dir, file), 'utf8')).trim().replace(/\s+/g, ' ')
  const uri = `data:image/svg+xml,${encodeURIComponent(svg).replace(/'/g, '%27')}`
  rules.push(`.zy-board[data-board='${name}'] {\n  --zy-board: url('${uri}');\n}`)
}

const css = `/* Generated by scripts/build-boards.mjs from boards/*.svg. Do not edit by hand. */

/* A faint board pattern behind the top of a page that fades out further down.
   Usage: <div class="zy-board" data-board="blueprint">. */
.zy-board {
  position: relative;
  isolation: isolate;
}

.zy-board::before {
  content: '';
  position: absolute;
  inset: 0;
  z-index: -1;
  pointer-events: none;
  background: var(--line-strong);
  opacity: var(--zy-board-opacity, 0.05);
  -webkit-mask-image: var(--zy-board), linear-gradient(to bottom, black 0, black 700px, transparent 1500px);
  mask-image: var(--zy-board), linear-gradient(to bottom, black 0, black 700px, transparent 1500px);
  -webkit-mask-composite: source-in;
  mask-composite: intersect;
  -webkit-mask-repeat: repeat, no-repeat;
  mask-repeat: repeat, no-repeat;
  -webkit-mask-position: center top, 0 0;
  mask-position: center top, 0 0;
  -webkit-mask-size: var(--zy-board-size, auto), 100% 100%;
  mask-size: var(--zy-board-size, auto), 100% 100%;
}

:root[data-theme='dark'] .zy-board::before {
  opacity: var(--zy-board-opacity-dark, 0.07);
}

@media (max-width: 860px) {
  .zy-board::before {
    opacity: 0.04;
  }
}

${rules.join('\n\n')}
`
await writeFile(join(root, 'boards.css'), css)
console.log(`boards.css: ${names.length} boards`)
